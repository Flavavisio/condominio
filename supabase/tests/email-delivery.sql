do $$
declare sa uuid:=gen_random_uuid(); resident uuid:=gen_random_uuid(); co uuid:=gen_random_uuid(); condo uuid:=gen_random_uuid(); a uuid:=gen_random_uuid(); notice uuid:=gen_random_uuid(); n uuid; row_count integer; claimed uuid;
begin
 insert into auth.users(id,email) values(sa,sa||'@example.invalid'),(resident,resident||'@example.invalid');
 update public.profiles set is_super_admin=true where user_id=sa;
 insert into public.companies(id,name,label) values(co,'Email test','Email test');
 insert into public.condominiums(id,company_id,name) values(condo,co,'Email test');
 insert into public.condominium_members(condominium_id,user_id) values(condo,resident);
 perform set_config('request.jwt.claim.sub',sa::text,true);
 set local role authenticated;
 insert into public.assemblies(id,condominium_id,title,scheduled_for,location,agenda,status) values(a,condo,'Test assembly',now()+interval '1 day','Hall','Agenda','draft');
 reset role;
 if exists(select 1 from public.notifications where condominium_id=condo) then raise exception 'TEST FAILED draft email';end if;
 set local role authenticated;
 update public.assemblies set status='scheduled' where id=a;
 update public.assemblies set status='scheduled' where id=a;
 insert into public.notices(id,condominium_id,title,body) values(notice,condo,'Test notice','Content');
