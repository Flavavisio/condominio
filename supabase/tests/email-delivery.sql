 select count(*) into row_count from public.notification_emails q join public.notifications n on n.id=q.notification_id where n.condominium_id=condo and n.user_id=resident;
 if row_count<>2 then raise exception 'TEST FAILED notification queue or dedup: %',row_count;end if;
 select id into n from public.notifications where condominium_id=condo limit 1;
 set local role service_role;
 if not public.can_receive_notification_email(n) then raise exception 'TEST FAILED recipient denied';end if;
